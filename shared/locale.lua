Locale = {}

Locale.Translate = function(str, ...)
    if Config.Translations[Config.Locale] and Config.Translations[Config.Locale][str] then
        return string.format(Config.Translations[Config.Locale][str], ...)
    end
    return str
end

-- Shorthand function
function _U(str, ...)
    return Locale.Translate(str, ...)
end
